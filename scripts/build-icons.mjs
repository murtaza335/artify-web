// Builds src/ui/icons.svg, an inline sprite of the few Lucide icons the app uses (ISC licence).
// Add a name to ICONS and rerun `npm run build:icons`.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'node_modules', 'lucide-static', 'icons');

const ICONS = [
  'sparkles', 'puzzle', 'paintbrush', 'shapes', 'heart', 'share-2', 'download', 'repeat', 'info', 'ellipsis',
  'code', 'bug', 'external-link', 'x', 'chevron-left', 'plus', 'undo-2', 'copy', 'flip-horizontal-2', 'trash-2',
  'bring-to-front', 'send-to-back', 'check', 'maximize', 'minimize', 'upload', 'eraser', 'eye', 'pencil', 'image',
  'arrow-right'
];

const symbols = ICONS.map((name) => {
  const src = readFileSync(join(dir, name + '.svg'), 'utf8');
  const body = src.slice(src.indexOf('>', src.indexOf('<svg')) + 1, src.lastIndexOf('</svg>')).replace(/\s*\n\s*/g, '').trim();
  return `<symbol id="i-${name}" viewBox="0 0 24 24">${body}</symbol>`;
});

const sprite = `<!-- Lucide icons (ISC licence, https://lucide.dev). Generated by scripts/build-icons.mjs. -->
<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" style="display:none" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">
${symbols.join('\n')}
</svg>
`;
writeFileSync(join(root, 'src', 'ui', 'icons.svg'), sprite);
console.log(`Wrote ${ICONS.length} icons to src/ui/icons.svg`);
