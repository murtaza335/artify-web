// Bundles the Artify extension's art engine (CommonJS) into one ES module for the web app.
// The engine is never forked: fix shapes in the extension repo, then run `npm run build:engine` here.
//
//   ARTIFY_DIR=/path/to/artify npm run build:engine
//
// The output is committed, so the site builds without the extension checked out.

import { build } from 'esbuild';
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const artify = resolve(process.env.ARTIFY_DIR || join(root, '..', 'artify'));
const out = join(root, 'src', 'vendor', 'artify-engine.js');

if (!existsSync(join(artify, 'src', 'forms.js'))) {
  console.error(`Artify extension not found at ${artify}. Set ARTIFY_DIR to its checkout.`);
  process.exit(1);
}

const pkg = JSON.parse(readFileSync(join(artify, 'package.json'), 'utf8'));
let commit = 'unknown';
try {
  commit = execFileSync('git', ['-C', artify, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim();
  const dirty = execFileSync('git', ['-C', artify, 'status', '--porcelain', 'src'], { encoding: 'utf8' }).trim();
  if (dirty) commit += '-dirty';
} catch {
  // Not a git checkout: the version is still recorded.
}

// One entry that re-exports the pieces the web app needs.
const p = (file) => JSON.stringify(join(artify, 'src', file));
const entry = `
export { compose, composeCreation, renderDesign, canonicalCategory, formIds, CATEGORIES, CATEGORY_LABELS, ANIMATION_CSS } from ${p('forms.js')};
export { Deck } from ${p('deck.js')};
export { Store, sanitizeCreation } from ${p('store.js')};
export { COLORS, COLOR_NAMES, makeRand } from ${p('shapes/engine.js')};
export { SHAPES, SHAPE_MAP } from ${p('shapes/library.js')};
`;

await build({
  stdin: { contents: entry, resolveDir: artify, loader: 'js' },
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2020',
  // Function names are form ids (the deck and saved designs use them), so they must survive minification.
  keepNames: true,
  minify: false,
  legalComments: 'none',
  outfile: out,
  banner: {
    js: `// GENERATED by scripts/build-engine.mjs. Do not edit: change the extension and rebuild.\n// Source: ${pkg.name} ${pkg.version} (${commit})\n/* eslint-disable */`
  }
});

console.log(`Wrote ${out} from ${pkg.name} ${pkg.version} (${commit})`);
